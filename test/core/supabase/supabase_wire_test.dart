import 'package:flutter_test/flutter_test.dart';
import 'package:legalhub/core/supabase/supabase_wire.dart';

void main() {
  test('table and bucket names pin the exact provider strings', () {
    const tables = <String>[
      SupabaseTables.matters,
      SupabaseTables.documents,
      SupabaseTables.files,
      SupabaseTables.billingInvoices,
      SupabaseTables.messageThreads,
      SupabaseTables.messages,
      SupabaseTables.notifications,
      SupabaseTables.tasks,
      SupabaseTables.consultationSlots,
      SupabaseTables.memberships,
    ];
    expect(tables, <String>[
      'matters',
      'documents',
      'files',
      'billing_invoices',
      'message_threads',
      'messages',
      'notifications',
      'tasks',
      'consultation_slots',
      'memberships',
    ]);
    expect(SupabaseBuckets.matterFiles, 'matter-files');
  });

  test('RPC names pin the exact provider strings', () {
    const rpcs = <String>[
      SupabaseRpcs.listApprovalRequests,
      SupabaseRpcs.createApprovalRequest,
      SupabaseRpcs.decideApprovalRequest,
      SupabaseRpcs.cancelApprovalRequest,
      SupabaseRpcs.listAttorneyProfiles,
      SupabaseRpcs.getAttorneyProfile,
      SupabaseRpcs.createAttorneyProfile,
      SupabaseRpcs.updateAttorneyProfile,
