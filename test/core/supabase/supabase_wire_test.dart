      'acknowledge_task',
    ]);

    const edgeFunctions = <String>[
      SupabaseEdgeFunctions.paymobInitiate,
      SupabaseEdgeFunctions.videoToken,
      SupabaseEdgeFunctions.researchAnalyze,
    ];
    expect(edgeFunctions, <String>[
      'paymob-initiate',
      'video-token',
      'research-analyze',
    ]);
