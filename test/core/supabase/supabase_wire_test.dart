      SupabaseRpcs.listComplianceAlerts,
      SupabaseRpcs.createComplianceAlert,
      SupabaseRpcs.acknowledgeComplianceAlert,
      SupabaseRpcs.resolveComplianceAlert,
      SupabaseRpcs.listVideoSessions,
      SupabaseRpcs.createVideoSession,
      SupabaseRpcs.markVideoSessionLive,
      SupabaseRpcs.endVideoSession,
      SupabaseRpcs.getInvoicePaymentStatus,
      SupabaseRpcs.listOrganizationsMetadata,
      SupabaseRpcs.listMembersMetadata,
      SupabaseRpcs.suspendMembershipPlatform,
      SupabaseRpcs.reactivateMembershipPlatform,
      SupabaseRpcs.deleteDemoAccount,
      SupabaseRpcs.readPlatformAudit,
      SupabaseRpcs.createOrganization,
      SupabaseRpcs.listOrgMembersMetadata,
      SupabaseRpcs.listMatterAssignableMembers,
      SupabaseRpcs.inviteMember,
      SupabaseRpcs.changeMemberRole,
      SupabaseRpcs.suspendMembership,
      SupabaseRpcs.reactivateMembership,
      SupabaseRpcs.removeMembership,
      SupabaseRpcs.resendInvitation,
      SupabaseRpcs.revokeInvitation,
      SupabaseRpcs.deleteMyAccount,
      SupabaseRpcs.acceptInvitation,
      SupabaseRpcs.readOrgAudit,
      SupabaseRpcs.createMatter,
      SupabaseRpcs.sendMessage,
      SupabaseRpcs.markNotificationsRead,
      SupabaseRpcs.registerMatterFile,
      SupabaseRpcs.bookConsultation,
      SupabaseRpcs.listResearchRuns,
      SupabaseRpcs.listResearchFindings,
      SupabaseRpcs.createTask,
      SupabaseRpcs.advanceTaskStatus,
      SupabaseRpcs.assignTask,
      SupabaseRpcs.acknowledgeTask,
